import { execFile } from 'node:child_process'
import { mkdir, rename, rm, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const account = 'ClydeQue'
const generatedPath = fileURLToPath(new URL('../src/data/githubActivity.js', import.meta.url))
const isoDatePattern = /^\d{4}-\d{2}-\d{2}$/

const dayIndex = (date) => Date.parse(`${date}T00:00:00Z`) / 86_400_000
const toUtcDate = (value = new Date()) => value.toISOString().slice(0, 10)
const isCanonicalIsoDate = (date) => {
  if (typeof date !== 'string' || !isoDatePattern.test(date)) return false
  const parsed = new Date(`${date}T00:00:00Z`)
  return !Number.isNaN(parsed.valueOf()) && parsed.toISOString().slice(0, 10) === date
}

export const calendarBounds = (year) => ({
  from: `${year}-01-01T00:00:00Z`,
  to: `${year}-12-31T23:59:59Z`,
})

const assertIsoDate = (date) => {
  if (!isCanonicalIsoDate(date)) throw new Error('GitHub contribution day must contain an ISO date')
}

const nonNegativeInteger = (value) => Number.isInteger(value) && value >= 0

const metricsFor = (contributionsByDate, year, snapshotDate) => {
  const activeDays = contributionsByDate.map(({ date }) => dayIndex(date))
  const activeDaySet = new Set(activeDays)
  let longestStreak = 0
  let streak = 0
  let previousDay

  for (const currentDay of activeDays) {
    streak = currentDay === previousDay + 1 ? streak + 1 : 1
    longestStreak = Math.max(longestStreak, streak)
    previousDay = currentDay
  }

  let currentStreak = 0
  if (Number.parseInt(snapshotDate.slice(0, 4), 10) === year) {
    for (let currentDay = dayIndex(snapshotDate); activeDaySet.has(currentDay); currentDay -= 1) currentStreak += 1
  }

  return {
    totalContributions: contributionsByDate.reduce((total, day) => total + day.contributions, 0),
    activeDays: contributionsByDate.length,
    currentStreak,
    longestStreak,
  }
}

export function normalizeContributionCalendar(contributionCalendar, { year, snapshotDate }) {
  if (!contributionCalendar || typeof contributionCalendar !== 'object') throw new Error('GitHub response is missing contributionCalendar')
  if (!Array.isArray(contributionCalendar.weeks)) throw new Error('GitHub contributionCalendar must contain weeks')

  const contributionsByDate = contributionCalendar.weeks.flatMap((week) => {
    if (!Array.isArray(week?.contributionDays)) throw new Error('GitHub contributionCalendar week must contain contributionDays')
    return week.contributionDays
      .filter((day) => {
        assertIsoDate(day?.date)
        if (!nonNegativeInteger(day?.contributionCount)) throw new Error('GitHub contribution day must contain a non-negative contributionCount')
        return day.contributionCount > 0
      })
      .map(({ date, contributionCount }) => ({ date, contributions: contributionCount }))
  }).sort((left, right) => left.date.localeCompare(right.date))

  if (new Set(contributionsByDate.map(({ date }) => date)).size !== contributionsByDate.length) throw new Error('GitHub contribution calendar contains duplicate dates')
  if (contributionsByDate.some(({ date }) => Number.parseInt(date.slice(0, 4), 10) !== year)) throw new Error(`GitHub contribution calendar contains dates outside ${year}`)

  return {
    year,
    ...calendarBounds(year),
    ...metricsFor(contributionsByDate, year, snapshotDate),
    contributionsByDate,
  }
}

export function buildSnapshot({ years, calendars, snapshotDate }) {
  if (!Array.isArray(years) || !calendars || typeof calendars.get !== 'function') throw new Error('GitHub snapshot requires contribution years and calendars')
  if (!isCanonicalIsoDate(snapshotDate)) throw new Error('GitHub snapshot requires an ISO snapshot date')

  const supportedYears = [...new Set(years.filter((year) => Number.isInteger(year)))].filter((year) => year >= 2024).sort((left, right) => left - right)
  if (supportedYears.length === 0) throw new Error('GitHub returned no supported contribution years')

  return {
    label: 'GitHub contribution activity',
    snapshotDate,
    description: 'Generated from GitHub contribution-calendar data. This committed snapshot is not a live activity feed.',
    years: supportedYears.map((year) => normalizeContributionCalendar(calendars.get(year), { year, snapshotDate })),
  }
}

export const formatSnapshotModule = (snapshot) => `// Generated by npm run sync:github-activity. Do not edit by hand.\nexport const githubActivity = ${JSON.stringify(snapshot, null, 2)}\n`

export async function writeSnapshotAtomically(destination, contents, { renameFile = rename } = {}) {
  const directory = dirname(destination)
  const temporaryPath = `${destination}.${process.pid}.tmp`
  await mkdir(directory, { recursive: true })

  try {
    await writeFile(temporaryPath, contents, 'utf8')
    await renameFile(temporaryPath, destination)
  } catch (error) {
    await rm(temporaryPath, { force: true })
    throw error
  }
}

const graphql = async (query, variables) => new Promise((resolve, reject) => {
  const argumentsList = ['api', 'graphql', '-f', `query=${query}`]
  for (const [key, value] of Object.entries(variables)) argumentsList.push('-F', `${key}=${value}`)
  const child = execFile('gh', argumentsList, { encoding: 'utf8', maxBuffer: 5 * 1024 * 1024 }, (error, stdout, stderr) => {
    if (error) return reject(new Error(`GitHub activity sync failed: ${stderr.trim() || error.message}`))
    try {
      resolve(JSON.parse(stdout))
    } catch {
      reject(new Error('GitHub activity sync failed: GitHub returned invalid JSON'))
    }
  })
  child.on('error', (error) => reject(new Error(`GitHub activity sync failed: ${error.message}`)))
})

const yearsQuery = 'query($login: String!) { user(login: $login) { contributionsCollection { contributionYears } } }'
const calendarQuery = 'query($login: String!, $from: DateTime!, $to: DateTime!) { user(login: $login) { contributionsCollection(from: $from, to: $to) { contributionCalendar { weeks { contributionDays { date contributionCount } } } } } }'

export async function syncGithubActivity({ now = new Date(), outputPath = generatedPath } = {}) {
  const snapshotDate = toUtcDate(now)
  const currentYear = Number.parseInt(snapshotDate.slice(0, 4), 10)
  const yearsResponse = await graphql(yearsQuery, { login: account })
  const contributionYears = yearsResponse?.data?.user?.contributionsCollection?.contributionYears
  if (!Array.isArray(contributionYears)) throw new Error('GitHub activity sync failed: contribution years were missing')

  const years = contributionYears.filter((year) => Number.isInteger(year) && year >= 2024 && year <= currentYear).sort((left, right) => left - right)
  if (years.length === 0) throw new Error('GitHub activity sync failed: no contribution years from 2024 onward')

  const calendars = new Map()
  for (const year of years) {
    const response = await graphql(calendarQuery, { login: account, ...calendarBounds(year) })
    const calendar = response?.data?.user?.contributionsCollection?.contributionCalendar
    if (!calendar) throw new Error(`GitHub activity sync failed: ${year} contribution calendar was missing`)
    calendars.set(year, calendar)
  }

  const snapshot = buildSnapshot({ years, calendars, snapshotDate })
  await writeSnapshotAtomically(outputPath, formatSnapshotModule(snapshot))
  return snapshot
}

const isDirectExecution = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isDirectExecution) {
  syncGithubActivity()
    .then((snapshot) => console.log(`GitHub contribution activity snapshot updated for ${snapshot.years.map(({ year }) => year).join(', ')}.`))
    .catch((error) => {
      console.error(error.message)
      process.exitCode = 1
    })
}
